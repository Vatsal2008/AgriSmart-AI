def group_for(crop, term):
    if term == "Healthy":
        return "healthy", "explicit"
    if f"{crop}::{term}" in CROP_TERMS:
        return CROP_TERMS[f"{crop}::{term}"], "crop-specific"
    if term in TERMS:
        return TERMS[term], "explicit"
    low = term.lower()
    for keys, group in RULES:
        if any(k in low for k in keys):
            return group, "rule"
    return "fungal_spot", "default"


def main():
    for key, vals in {**T, **UI}.items():
        assert len(vals) == len(LANGS), f"{key}: {len(vals)} languages"
    for group, steps in GROUPS.items():
        for key, _ in steps:
            assert key in T, f"group {group} uses unknown step {key}"

    crops = json.loads(CROPS_JSON.read_text(encoding="utf-8"))
    terms, crop_terms, how = {}, {}, {}
    for crop, labels in crops.items():
        for label in labels:
            group, why = group_for(crop, label)
            how.setdefault(why, []).append(f"{crop}::{label} -> {group}")
            if why == "crop-specific":
                crop_terms[f"{crop}::{label}"] = group
            else:
                terms[label] = group
    advice = {
        "note": "DRAFT, not yet reviewed by an agronomist. Doses follow standard extension recommendations "
                "(per litre of water unless stated); always follow the product label and local advice.",
        "languages": LANGS,
        "templates": {k: dict(zip(LANGS, v)) for k, v in T.items()},
        "groups": GROUPS,
        "terms": dict(sorted(terms.items())),
        "crop_terms": crop_terms,
        "default": "fungal_spot",
    }
    OUT.write_text(json.dumps(advice, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    raw = TRANSLATIONS.read_text(encoding="utf-8")
    indent = len(raw.split("\n")[1]) - len(raw.split("\n")[1].lstrip()) or None
    tr = json.loads(raw)
    for key, vals in UI.items():
        tr["ui"][key] = dict(zip(LANGS, vals))
    TRANSLATIONS.write_text(json.dumps(tr, ensure_ascii=False, indent=indent) + "\n", encoding="utf-8")

    n = sum(len(v) for v in crops.values())
    print(f"advice for {n} classes across {len(crops)} crops -> {OUT.name}: {len(terms)} disease names, "
          f"{len(crop_terms)} crop-specific, {len(GROUPS)} treatment groups, {len(T)} step templates x {len(LANGS)} languages")
    used = Counter(g for g in list(terms.values()) + list(crop_terms.values()))
    print("classes per group:", dict(sorted(used.items(), key=lambda kv: -kv[1])))
    for why in ("rule", "default"):
        print(f"\n--- decided by {why} ({len(how.get(why, []))}) ---")
        for line in sorted(set(how.get(why, []))):
            print("  " + line)


if __name__ == "__main__":
    from collections import Counter
    main()
