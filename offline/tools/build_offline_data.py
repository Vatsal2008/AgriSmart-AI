# labels of removed features (the key-based online check, the list of classes the model weighed): dropped from the
# shared translations file too
OBSOLETE_UI = ["online_agrees", "online_corrected", "online_new_plant", "settings", "save", "keys_hint", "ai_note",
               "statistics"]
# spoken status phrases that already exist as screen labels in the translations file
SPOKEN_UI = ["which_crop", "which_crop_hint", "crop_mismatch", "not_sure", "healthy_result", "cause_title",
             "advice_title", "too_dark", "too_blurry", "confirm_crop"]


def spoken_product(product, lang):
    en, dev, urd = PRODUCTS[product]
    if lang == "en":
        return en
    if lang == "ur":
        return urd
    if lang in ("hi", "mr"):
        return HINDI_WORDS.get(product, dev)
    text = dev.replace("़", "").replace("ॉ", "ो").replace("ऑ", "ओ")  # nukta, candra o
    if lang in ("te", "ta", "kn", "ml"):  # these scripts read a final consonant with "a"; add a virama to stop it
        text = re.sub(r"([क-ह])(?=\s|$)", "\\1्", text)
    out = sanscript.transliterate(text, sanscript.DEVANAGARI, SCRIPT[lang])
    if lang == "as":  # Assamese letters for ra / wa
        out = out.replace("র", "ৰ")
    return out


def main():
    tr = json.loads((SRV / "india_translations.json").read_text(encoding="utf-8"))
    adv = json.loads((SRV / "india_advice.json").read_text(encoding="utf-8"))
    for key, vals in {**CAUSES, **SAY, **UI, **DAYS}.items():
        assert len(vals) == len(LANGS), f"{key}: {len(vals)} languages"
    for g in adv["groups"]:
        assert g in GROUP_CAUSE or g == "healthy", f"group {g} has no cause"
    for key, vals in UI.items():
        tr["ui"][key] = dict(zip(LANGS, vals))
    for key in OBSOLETE_UI:
        tr["ui"].pop(key, None)
    # the live-scan server page shares these labels (yes/no crop question...): keep its file in step
    server_tr = SRV / "india_translations.json"
    text = json.dumps(tr, ensure_ascii=False, indent=1)
    if server_tr.read_text(encoding="utf-8").rstrip("\n") != text:
        server_tr.write_text(text, encoding="utf-8")

    products_used = {p["chem"] for steps in adv["groups"].values() for _, p in steps if p.get("chem")}
    missing = products_used - set(PRODUCTS)
    assert not missing, f"products without a spoken name: {missing}"

    app = {
        "languages": tr["languages"], "ui": tr["ui"], "crops": tr["crops"], "terms": tr["terms"],
        "advice": {k: adv[k] for k in ("templates", "groups", "terms", "crop_terms", "default")},
        "causes": {"templates": {k: dict(zip(LANGS, v)) for k, v in CAUSES.items()},
                   "groups": GROUP_CAUSE, "terms": TERM_CAUSE},
        "note": adv.get("note", ""),
    }
    (OUT / "app.json").write_text(json.dumps(app, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

    # every phrase the voice may say, per language, keyed the way the page asks for audio
    inv = {lang: {} for lang in LANGS}
    li = {lang: i for i, lang in enumerate(LANGS)}
    for lang in LANGS:
        d = inv[lang]
        for cid, row in tr["crops"].items():
            d[f"crop:{cid}"] = row.get(lang) or row["en"]
        for term, row in tr["terms"].items():
            d[f"term:{term}"] = row.get(lang) or row["en"]
        for cat, vals in CAUSES.items():
            d[f"cause:{cat}"] = vals[li[lang]]
        for key in SPOKEN_UI:
            row = tr["ui"].get(key)
            if row:
                d[f"ui:{key}"] = row.get(lang) or row["en"]
        for group, steps in adv["groups"].items():
            for i, (key, params) in enumerate(steps):
                if key in SAY:
                    text = SAY[key][li[lang]].replace("{chem}", spoken_product(params["chem"], lang)
                                                      if params.get("chem") else "")
                else:
                    text = adv["templates"][key].get(lang) or adv["templates"][key]["en"]
                    if "{days}" in text:
                        text = text.replace("{days}", DAYS[str(params["days"])][li[lang]])
                    for k, v in params.items():
                        text = text.replace("{" + k + "}", str(v))
                if re.search(r"[0-9]", text):
                    raise AssertionError(f"digits left in spoken text {lang} {group}/{i}: {text}")
                d[f"step:{group}:{i}"] = text
    (BUILD / "speech_inventory.json").write_text(json.dumps(inv, ensure_ascii=False, indent=1), encoding="utf-8")
    n_unique = sum(len(set(d.values())) for d in inv.values())
    print(f"app.json: {len(tr['crops'])} crops, {len(tr['terms'])} disease names, {len(adv['groups'])} treatment groups, "
          f"{len(CAUSES)} causes, {len(tr['ui'])} screen labels, {len(LANGS)} languages "
          f"({(OUT / 'app.json').stat().st_size / 1e6:.2f} MB)")
    print(f"speech inventory: {sum(len(d) for d in inv.values())} phrases, {n_unique} unique texts to record")
    print("spoken product names, e.g. Mancozeb:", {lang: spoken_product("Mancozeb 75% WP", lang) for lang in LANGS})


if __name__ == "__main__":
    main()
